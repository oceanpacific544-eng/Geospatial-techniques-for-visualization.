export function calculateFormulaImpactScore(
  waterPresence: 'none' | 'low' | 'medium' | 'high',
  vegetationPercent: number,
  condition: 'good' | 'moderate' | 'poor',
  soilErosionSigns: boolean
): number {
  const waterMap = { none: 0, low: 33, medium: 66, high: 100 };
  const condMap = { poor: 25, moderate: 65, good: 100 };
  
  const waterVal = waterMap[waterPresence];
  const condVal = condMap[condition];
  const erosionVal = soilErosionSigns ? 0 : 100; // (1 - Erosion)
  
  // Formula: 0.3*Water + 0.3*Vegetation + 0.2*Condition + 0.2*(1 - Erosion)
  const score = 0.3 * waterVal + 0.3 * vegetationPercent + 0.2 * condVal + 0.2 * erosionVal;
  return Math.round(score);
}
